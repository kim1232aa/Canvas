import { PROVIDER_TITLE_LABEL, friendlyProviderLabel, checkpointNodeTitle } from './providerLabels';
import { NODE_TITLE_MAP } from './nodeUiLabels';

/**
 * Checks whether an existing title of an AIVideoNode was generated from
 * the preset template or node definition (e.g. `AI 视频 (Fal.ai)`, `AI 视频`, `AI 视频（显式 Provider/Model）`),
 * as opposed to a custom name explicitly typed by the user.
 */
export function isTemplateVideoNodeTitle(title: string | undefined | null): boolean {
  const raw = String(title || '').trim();
  if (!raw) return true;
  if (raw === 'AI 视频') return true;

  // Pattern: AI 视频 (...) or AI 视频（...）
  const match = raw.match(/^AI 视频\s*[(（](.+)[)）]$/);
  if (!match) return false;

  const inner = match[1].trim();
  // If the parenthesized content matches any known provider key or friendly label,
  // it was generated by preset template `AI 视频 (${friendly(provider)})`
  if (PROVIDER_TITLE_LABEL[inner]) return true;
  if (Object.values(PROVIDER_TITLE_LABEL).includes(inner)) return true;

  // Also check case-insensitive match for provider keys (e.g. 'sogni', 'fal')
  const lowerInner = inner.toLowerCase();
  for (const [key, label] of Object.entries(PROVIDER_TITLE_LABEL)) {
    if (key.toLowerCase() === lowerInner || label.toLowerCase() === lowerInner) {
      return true;
    }
  }

  // Content inside parentheses is not a recognized provider name (e.g. "我的测试"),
  // meaning it's a user-renamed title.
  return false;
}

/**
 * Formats the display title for an AIVideoNode:
 * - If the title was renamed by the user, keeps the user's title untouched.
 * - If the title was generated from preset template, updates dynamically to follow the current provider.
 */
export function formatVideoNodeTitle(
  currentTitle: string | undefined | null,
  provider: string | undefined | null
): string {
  const raw = String(currentTitle || '').trim();
  // Preserve user-renamed titles
  if (raw && !isTemplateVideoNodeTitle(raw)) {
    return raw;
  }

  const prov = String(provider || '').trim();
  if (!prov) return 'AI 视频';
  const label = friendlyProviderLabel(prov);
  return `AI 视频 (${label})`;
}

/**
 * Checks whether an existing title of a CheckpointLoaderSimple was generated from
 * the preset template, checkpointNodeTitle, or node definition,
 * as opposed to a custom name explicitly typed by the user.
 */
export function isTemplateCheckpointNodeTitle(title: string | undefined | null): boolean {
  const raw = String(title || '').trim();
  if (!raw) return true;
  if (raw === '加载底模' || raw === '加载 Checkpoint' || raw === '加载底模 (Checkpoint)') return true;

  // Replicate pattern: Load Checkpoint (Replicate · ...) or Load Checkpoint (Replicate) or Load Checkpoint
  if (/^Load Checkpoint(\s*[(（].*[)）])?$/i.test(raw)) return true;

  const match = raw.match(/^加载底模\s*[(（](.+)[)）]$/);
  if (!match) return false;

  const inner = match[1].trim();
  if (PROVIDER_TITLE_LABEL[inner] || Object.values(PROVIDER_TITLE_LABEL).includes(inner)) return true;
  // If it's a model name / filename (e.g. from checkpointNodeTitle('', ckpt)), it's also template-generated
  if (/^[a-zA-Z0-9_\-./]+$/.test(inner)) return true;

  return false;
}

/**
 * Formats the display title for a CheckpointLoaderSimple node:
 * - If the title was renamed by the user, keeps the user's title untouched.
 * - If the title was generated from preset template, updates dynamically to follow current provider / checkpoint.
 */
export function formatCheckpointNodeTitle(
  currentTitle: string | undefined | null,
  provider: string | undefined | null,
  checkpoint?: string | undefined | null
): string {
  const raw = String(currentTitle || '').trim();
  if (raw && !isTemplateCheckpointNodeTitle(raw)) {
    return raw;
  }
  return checkpointNodeTitle(provider, checkpoint);
}

/**
 * Enhanced formatNodeDisplayTitle:
 * General entry point for resolving display titles across all node types.
 * - AIVideoNode: follows provider if template-generated; preserves custom titles.
 * - CheckpointLoaderSimple: follows provider/checkpoint if template-generated; preserves custom titles.
 * - Presets/nodes without provider suffix (e.g. SaveImage, SaveVideo, KSampler): unchanged.
 * - Backward compatible: if values are omitted, falls back to NODE_TITLE_MAP or currentTitle.
 */
export function formatNodeDisplayTitle(
  type: string,
  currentTitle?: string,
  values?: any
): string {
  if (type === 'AIVideoNode') {
    const prov = values?.targetProvider || values?.provider;
    if (prov !== undefined) {
      return formatVideoNodeTitle(currentTitle, prov);
    }
  }

  if (type === 'CheckpointLoaderSimple') {
    if (values && (values.targetProvider !== undefined || values.ckpt_name !== undefined)) {
      return formatCheckpointNodeTitle(currentTitle, values.targetProvider, values.ckpt_name);
    }
  }

  if (NODE_TITLE_MAP[type]) {
    return NODE_TITLE_MAP[type];
  }

  return currentTitle || type;
}
